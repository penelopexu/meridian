const CN_PROV_PREFIX = /^(内蒙古|黑龙江|北京|天津|河北|山西|辽宁|吉林|上海|江苏|浙江|安徽|福建|江西|山东|河南|湖北|湖南|广东|广西|海南|重庆|四川|贵州|云南|西藏|陕西|甘肃|青海|宁夏|新疆)(壮族|回族|维吾尔|)(省|市|自治区|)/;
const CN_ADMIN_SUFFIX = /(自治县|自治旗|联合旗|特区|林区|矿区|新区|区|县|市|旗)$/;
const CN_ETHNIC_TOKEN = /(土家族|布依族|柯尔克孜族|鄂温克族|鄂伦春族|达斡尔族|塔吉克族|撒拉族|维吾尔族|哈萨克族|朝鲜族|仫佬族|毛南族|仡佬族|锡伯族|裕固族|东乡族|保安族|普米族|纳西族|拉祜族|哈尼族|阿昌族|德昂族|基诺族|独龙族|景颇族|傈僳族|蒙古族|苗族|侗族|彝族|白族|傣族|藏族|羌族|回族|满族|畲族|黎族|壮族|瑶族|水族|京族|佤族|怒族|锡伯|各族)$/;

/* 去掉"区/县/市/旗/自治县…"等行政后缀和民族名，剩不到两个字就原样返回 */
function cnStripAdmin(s){
  let t=s.replace(CN_ADMIN_SUFFIX,'');
  if(t.length<1) return s;
  for(let i=0;i<4;i++){
    const m=t.match(CN_ETHNIC_TOKEN);
    if(!m || t.length-m[0].length<2) break;
    t=t.slice(0,t.length-m[0].length);
  }
  if(t.length>2 && t.endsWith('族')) t=t.slice(0,-1);
  return t.length<1 ? s : t;
}

/* 生成查询候选：原样 / 去后缀 / 去省份前缀 / 去省份前缀再去后缀 */
function cnDistrictKeys(q){
  const s=String(q||'').trim().replace(/\s+/g,'');
  if(!s) return [];
  const out=[s];
  const t=cnStripAdmin(s); if(t!==s) out.push(t);
  const m=s.match(CN_PROV_PREFIX);
  if(m && m[0].length<s.length){
    const rest=s.slice(m[0].length);
    if(rest){ out.push(rest); const r2=cnStripAdmin(rest); if(r2!==rest) out.push(r2); }
  }
  return out;
}

/* 查区县所属地级市，返回字符串；查不到返回 null。
   输入可带或不带"区/县/市/旗"后缀，也可带省份前缀：惠阳 / 惠阳区 / 广东惠阳 → 惠州 */
function districtToCity(q){
  const all=districtToCityAll(q);
  return all.length ? all[0] : null;
}

/* 同上，但把重名的多个候选都返回（数组，按可能性从高到低） */
function districtToCityAll(q){
  for(const k of cnDistrictKeys(q)){
    const v=CN_DISTRICT[k];
    if(v) return v.split('|');
  }
  return [];
}
